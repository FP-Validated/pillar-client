#!/usr/bin/env node
// Verifies that every generated LayerZero config file still agrees with its own
// provenance header.
//
// The generators write a header that declares how many rows they emitted. This check
// re-counts the rows and compares. It exists because a hand-edit is the failure mode the
// repository's own guidance calls out - "do not hand-edit
// crates/pillar-config/src/generated_layerzero_evm.rs; regenerate it from the script" -
// and nothing enforced it. Adding or deleting a row here changes a signing-critical
// address table, and a wrong trusted-emitter or ULN address is a security bug, not a
// cosmetic one.
//
// Deliberately self-contained: no upstream checkout, no npm package, no network. The two
// existing checkers (check-layerzero-environment-parity.mjs, check-parity-coverage.mjs)
// both require PILLAR_AUDIT_ROOT, the private TypeScript service checkout, so neither can
// run in CI. This one can, which is the whole point of it being a separate script rather
// than another branch inside those.
//
// What it does NOT do: prove the values are correct. Only regenerating from the pinned
// upstream package does that. This catches drift between a file and its own header.

import fs from 'node:fs'
import path from 'node:path'

const repoRoot = process.cwd()
const configDir = path.join(repoRoot, 'crates', 'pillar-config', 'src')

// file -> generator it must declare, and each (header label, array) pair to reconcile.
const EXPECTED = [
    {
        file: 'generated_layerzero_evm.rs',
        generator: 'scripts/generate-layerzero-static-config.mjs',
        counts: [
            ['Endpoint entries', 'LZ_EVM_ENDPOINT_IDS'],
            ['Deployment entries', 'LZ_EVM_DEPLOYMENT_ADDRESSES'],
        ],
    },
    {
        file: 'generated_layerzero_environment.rs',
        generator: 'scripts/generate-layerzero-environment-capability.mjs',
        counts: [['Entries', 'LZ_ENVIRONMENT_ULN_CHAIN_STATUS']],
    },
    {
        file: 'generated_ton_layerzero.rs',
        generator: 'scripts/generate-ton-static-config.mjs',
        counts: [
            ['Code cells', 'TON_CODE_CELLS'],
            ['Deployments', 'TON_DEPLOYMENTS'],
        ],
    },
]

const failures = []

function fail(message) {
    failures.push(message)
}

/** Rows in a `const NAME: &[...] = &[ ... ];` literal, counted as top-level tuples. */
function countRows(text, name, file) {
    const declStart = text.indexOf(`const ${name}:`)
    if (declStart < 0) {
        fail(`${file}: expected generated array ${name} is missing`)
        return null
    }
    const open = text.indexOf('&[', declStart)
    const end = text.indexOf('\n];', open)
    if (open < 0 || end < 0) {
        fail(`${file}: could not delimit the ${name} literal`)
        return null
    }
    return text
        .slice(open, end)
        .split('\n')
        .filter((line) => /^\s+\(/.test(line)).length
}

function declaredCount(text, label, file) {
    const match = text.match(new RegExp(`^// ${label}: (\\d+)$`, 'm'))
    if (!match) {
        fail(`${file}: provenance header does not declare "${label}"`)
        return null
    }
    return Number(match[1])
}

// A file that lost its provenance header would silently pass every count check, so the
// marker and the generator attribution are verified before the counts.
function checkHeader(text, spec) {
    if (!text.startsWith('// @generated by ')) {
        fail(`${spec.file}: missing the leading "// @generated by" marker`)
        return
    }
    if (!text.includes(`// @generated by ${spec.generator}`)) {
        fail(`${spec.file}: is not attributed to ${spec.generator}`)
    }
    if (!/^\/\/ Provenance:$/m.test(text)) {
        fail(`${spec.file}: provenance block is missing`)
    }
    // Every generator records at least one input digest; losing them would make the file
    // unreproducible without any count changing. The generators disagree on spacing -
    // the EVM and environment headers write `sha256:<hex>` in a bulleted list while the
    // TON header writes `... sha256: <hex>` inline - so both are accepted.
    if (!/sha256:\s?[0-9a-f]{64}/.test(text)) {
        fail(`${spec.file}: provenance block records no sha256 input digest`)
    }
}

let checked = 0
for (const spec of EXPECTED) {
    const filePath = path.join(configDir, spec.file)
    if (!fs.existsSync(filePath)) {
        fail(`${spec.file}: expected generated file is missing from ${configDir}`)
        continue
    }
    const text = fs.readFileSync(filePath, 'utf8')
    checkHeader(text, spec)
    for (const [label, array] of spec.counts) {
        const declared = declaredCount(text, label, spec.file)
        const actual = countRows(text, array, spec.file)
        if (declared === null || actual === null) continue
        checked += 1
        if (declared !== actual) {
            fail(
                `${spec.file}: header declares ${label} = ${declared} but ${array} holds ${actual} rows. ` +
                    `Regenerate with ${spec.generator} instead of editing the file.`,
            )
        } else {
            console.log(`ok  ${spec.file}  ${label}: ${declared} == ${array} rows`)
        }
    }
}

if (failures.length > 0) {
    console.error('\ngenerated config integrity check FAILED:')
    for (const message of failures) console.error(`  - ${message}`)
    process.exit(1)
}

console.log(`\ngenerated config integrity check passed: ${checked} counts reconciled`)
