// Generates the table behind upstream's v1 chain-id resolution:
// `getChainName(id)` = lz-definitions `getNetworkForChainId(parseInt(id)).chainName`
// (`static-config/src/index.ts:50-53`), which answers a ULN v1 chain id (eid - 100)
// and every EndpointId. The table records that function's own answer for every id
// it accepts; any other id is its `Invalid endpointId` invariant.
import fs from 'node:fs'
import path from 'node:path'
import Module from 'node:module'
import { createHash } from 'node:crypto'

const repoRoot = process.cwd()
const definitionsRoot = process.env.LZ_DEFINITIONS_ROOT
const outputPath = path.join(
    repoRoot,
    'crates/pillar-config/src/generated_layerzero_legacy_chain_ids.rs',
)

function fail(message) {
    console.error(`generate-layerzero-legacy-chain-ids: ${message}`)
    process.exit(1)
}

if (!definitionsRoot) fail('LZ_DEFINITIONS_ROOT must point at an extracted @layerzerolabs/lz-definitions package')
const packageJson = JSON.parse(fs.readFileSync(path.join(definitionsRoot, 'package.json'), 'utf8'))
if (packageJson.name !== '@layerzerolabs/lz-definitions') fail(`unexpected package ${packageJson.name}`)
const distPath = path.join(definitionsRoot, 'dist/index.cjs')
const dist = fs.readFileSync(distPath)

// The bundle's only import; tiny-invariant 1.3.1 outside production throws exactly this.
const resolveFilename = Module._resolveFilename
Module._resolveFilename = function (request, ...rest) {
    if (request === 'tiny-invariant') return 'tiny-invariant'
    return resolveFilename.call(this, request, ...rest)
}
Module._cache['tiny-invariant'] = {
    id: 'tiny-invariant',
    filename: 'tiny-invariant',
    loaded: true,
    exports: (condition, message) => {
        if (!condition) throw new Error(`Invariant failed: ${message}`)
    },
}
const definitions = Module.createRequire(distPath)(distPath)

const candidates = new Set()
for (const key of Object.keys(definitions.EndpointId)) {
    const id = Number(key)
    if (Number.isInteger(id) && String(id) === key) candidates.add(id)
}
for (const endpointId of definitions.ULN_V1_CHAINS) candidates.add(endpointId - 100)

const rows = []
for (const id of [...candidates].sort((a, b) => a - b)) {
    let network
    try {
        network = definitions.getNetworkForChainId(id)
    } catch {
        continue
    }
    if (!network || typeof network.chainName !== 'string') fail(`id ${id} resolved without a chain name`)
    if (id < 0 || id > 0xffffffff) fail(`id ${id} does not fit u32`)
    rows.push([id, network.chainName])
}

const lines = [
    '// @generated by scripts/generate-layerzero-legacy-chain-ids.mjs',
    '// Provenance:',
    `// Upstream: ${packageJson.name}@${packageJson.version} getNetworkForChainId`,
    '//   over every EndpointId and every ULN_V1_CHAINS entry minus 100.',
    '// Input hashes:',
    `// - dist/index.cjs sha256:${createHash('sha256').update(dist).digest('hex')}`,
    `// Entries: ${rows.length}`,
    '',
    'pub(crate) const LZ_LEGACY_CHAIN_NAME_BY_ID: &[(u32, &str)] = &[',
    ...rows.map(([id, chain]) => `    (${id}, ${JSON.stringify(chain)}),`),
    '];',
    '',
]
fs.writeFileSync(outputPath, lines.join('\n'))
console.log(`wrote ${rows.length} legacy chain ids to ${outputPath}`)
