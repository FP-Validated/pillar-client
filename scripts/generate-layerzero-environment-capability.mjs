import fs from 'node:fs'
import path from 'node:path'
import { createHash } from 'node:crypto'

const repoRoot = process.cwd()
const sourceRoot = path.resolve(
    process.env.PILLAR_AUDIT_ROOT ?? path.join(repoRoot, '../pillar-audit'),
)
const outputPath = path.join(
    repoRoot,
    'crates/pillar-config/src/generated_layerzero_environment.rs',
)
const environments = ['mainnet', 'testnet', 'sandbox']

function fail(message) {
    console.error(`generate-layerzero-environment-capability: ${message}`)
    process.exit(1)
}

function inputPath(environment) {
    return path.join(
        sourceRoot,
        `packages/static-config/src/chainNames/${environment}.ts`,
    )
}

function sha256(raw) {
    return createHash('sha256').update(raw).digest('hex')
}

function loadChainNames(environment) {
    const filePath = inputPath(environment)
    if (!fs.existsSync(filePath)) {
        fail(`chainNames input does not exist: ${filePath}`)
    }
    const raw = fs.readFileSync(filePath, 'utf8')
    const assignment = raw.indexOf('=')
    if (assignment < 0) {
        fail(`chainNames input has no assignment: ${filePath}`)
    }
    const objectText = raw.slice(assignment + 1).trim().replace(/;$/, '')
    let parsed
    try {
        parsed = Function(`"use strict"; return (${objectText})`)()
    } catch (error) {
        fail(`cannot parse ${filePath}: ${error instanceof Error ? error.message : error}`)
    }
    return { raw, parsed }
}

function scanEntries(raw, parsed, environment) {
    const scanned = []
    let currentVersion = null
    for (const [index, line] of raw.split('\n').entries()) {
        const version = line.match(/^\s*(V2|V301|V302|ReadV1002):\s*\{$/)
        if (version) {
            currentVersion = version[1]
            continue
        }
        const chain = line.match(/^\s*([A-Za-z0-9_]+):\s*'([^']+)',?$/)
        if (currentVersion && chain && parsed[currentVersion]?.[chain[1]] === chain[2]) {
            scanned.push([environment, currentVersion, chain[1], chain[2], index + 1])
        }
    }
    const expected = Object.values(parsed).reduce(
        (count, chains) => count + Object.keys(chains).length,
        0,
    )
    if (scanned.length !== expected) {
        fail(`parsed ${expected} entries but located ${scanned.length} source lines for ${environment}`)
    }
    return scanned
}

const inputs = []
const entries = []
for (const environment of environments) {
    const { raw, parsed } = loadChainNames(environment)
    inputs.push({ environment, sha256: sha256(raw) })
    entries.push(...scanEntries(raw, parsed, environment))
}

const lines = [
    '// @generated by scripts/generate-layerzero-environment-capability.mjs',
    '// Provenance:',
    '// Upstream: per-environment LayerZero chain-name capability configuration',
    '//   of the upstream TypeScript service. It is not a published package, so',
    '//   the inputs are identified by content hash rather than by version.',
    '// Input hashes:',
    ...inputs.map(({ environment, sha256 }) => `// - ${environment} sha256:${sha256}`),
    `// Entries: ${entries.length}`,
    '',
    'pub(crate) const LZ_ENVIRONMENT_ULN_CHAIN_STATUS: &[(&str, &str, &str, &str, u32)] = &[',
]
for (const [environment, ulnVersion, chainName, status, sourceLine] of entries) {
    lines.push(
        `    ("${environment}", "${ulnVersion}", "${chainName}", "${status}", ${sourceLine}),`,
    )
}
lines.push('];', '')

fs.mkdirSync(path.dirname(outputPath), { recursive: true })
fs.writeFileSync(outputPath, lines.join('\n'))
console.log(`wrote ${entries.length} environment capability entries to ${outputPath}`)
