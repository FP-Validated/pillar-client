// Generates the per-environment `maxEthGetLogsBlockRange` table upstream reads through
// `LocalChainMetadataConfigGetter` (`apps/gasolina/src/index.ts:35-43`) from
// `@offchain-monorepo/chain-metadata-config-values` `src/<environment>/chainMetadataConfig.json`.
// A chain absent from that file has no range; upstream's getter throws reading it.
import fs from 'node:fs'
import path from 'node:path'
import { createHash } from 'node:crypto'

const repoRoot = process.cwd()
const valuesRoot = process.env.CHAIN_METADATA_ROOT
const outputPath = path.join(repoRoot, 'crates/pillar-config/src/generated_chain_metadata.rs')
const ENVIRONMENTS = ['mainnet', 'testnet', 'sandbox']

function fail(message) {
    console.error(`generate-chain-metadata-config: ${message}`)
    process.exit(1)
}

if (!valuesRoot) fail('CHAIN_METADATA_ROOT must point at chain-metadata-config/values/src')

const hashes = []
const rows = []
for (const environment of ENVIRONMENTS) {
    const file = path.join(valuesRoot, environment, 'chainMetadataConfig.json')
    const raw = fs.readFileSync(file)
    hashes.push([environment, createHash('sha256').update(raw).digest('hex')])
    const config = JSON.parse(raw.toString('utf8'))
    for (const chainName of Object.keys(config).sort()) {
        const range = config[chainName].maxEthGetLogsBlockRange
        if (!Number.isInteger(range) || range < 0 || range > 0xffffffff) {
            fail(`${environment}/${chainName}: maxEthGetLogsBlockRange ${range} is not a u32`)
        }
        rows.push([environment, chainName, range])
    }
}

const lines = [
    '// @generated by scripts/generate-chain-metadata-config.mjs',
    '// Provenance:',
    '// Upstream: chain metadata configuration of the upstream TypeScript service',
    '//   (`maxEthGetLogsBlockRange` only). It is not a published package, so the',
    '//   inputs are identified by content hash rather than by version.',
    '// Input hashes:',
    ...hashes.map(([environment, hash]) => `// - ${environment} sha256:${hash}`),
    `// Entries: ${rows.length}`,
    '',
    'pub(crate) const CHAIN_MAX_ETH_GET_LOGS_BLOCK_RANGE: &[(&str, &str, u32)] = &[',
    ...rows.map(([environment, chain, range]) => `    (${JSON.stringify(environment)}, ${JSON.stringify(chain)}, ${range}),`),
    '];',
    '',
]
fs.writeFileSync(outputPath, lines.join('\n'))
console.log(`wrote ${rows.length} chain metadata rows to ${outputPath}`)
